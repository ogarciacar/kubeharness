// Command render writes the manifest layers that internal/profile embeds,
// from the pins in profile.Pinned(). It downloads each Gateway API install
// manifest and checks its sha256, and pulls each Helm chart, checks its
// digest, and templates it with the Helm SDK. Tests never run Helm or reach
// the network for manifests.
//
// Run it from the repository root after changing a pin:
//
//	go -C hack/render run .
//
// With -check it writes nothing and exits 1 when the committed layers differ
// from a fresh render.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"time"

	"helm.sh/helm/v4/pkg/action"
	"helm.sh/helm/v4/pkg/chart/v2/loader"
	"helm.sh/helm/v4/pkg/registry"
	release "helm.sh/helm/v4/pkg/release/v1"
	"helm.sh/helm/v4/pkg/strvals"
	"sigs.k8s.io/yaml"

	"github.com/ogarciacar/kubeharness/internal/profile"
)

const generated = "# Code generated by hack/render. DO NOT EDIT.\n"

func main() {
	check := flag.Bool("check", false, "compare the committed layers with a fresh render instead of writing them")
	dir := flag.String("dir", "../../internal/profile/manifests", "the manifests directory that internal/profile embeds")
	flag.Parse()
	if err := run(*dir, *check); err != nil {
		fmt.Fprintln(os.Stderr, "render:", err)
		os.Exit(1)
	}
}

func run(dir string, check bool) error {
	reg, err := registry.NewClient()
	if err != nil {
		return err
	}
	want := map[string][]byte{}
	handWritten := map[string]bool{}
	for _, p := range profile.Pinned() {
		if _, done := want[p.GatewayAPI.Path()]; !done {
			if want[p.GatewayAPI.Path()], err = gatewayAPI(p.GatewayAPI); err != nil {
				return err
			}
		}
		for _, c := range []profile.Chart{p.ControllerCRDs, p.Controller} {
			if want[c.Path], err = chart(reg, c); err != nil {
				return err
			}
		}
		handWritten[p.Class] = true
	}

	var problems []string
	for path := range handWritten {
		if _, err := os.Stat(filepath.Join(dir, path)); err != nil {
			problems = append(problems, fmt.Sprintf("hand-written layer %s: %v", path, err))
		}
	}
	for _, path := range slices.Sorted(func(yield func(string) bool) {
		for p := range want {
			if !yield(p) {
				return
			}
		}
	}) {
		file := filepath.Join(dir, path)
		have, err := os.ReadFile(file)
		if err == nil && bytes.Equal(have, want[path]) {
			continue
		}
		if check {
			problems = append(problems, path+" differs from a fresh render")
			continue
		}
		if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(file, want[path], 0o644); err != nil {
			return err
		}
		fmt.Println("wrote", path)
	}
	stale, err := staleFiles(dir, want, handWritten)
	if err != nil {
		return err
	}
	for _, path := range stale {
		if check {
			problems = append(problems, path+" is not a layer of any pinned recipe")
			continue
		}
		if err := os.Remove(filepath.Join(dir, path)); err != nil {
			return err
		}
		fmt.Println("removed", path)
	}
	if len(problems) > 0 {
		return errors.New(strings.Join(problems, "\n") + "\nrun: go -C hack/render run .")
	}
	return nil
}

func staleFiles(dir string, rendered map[string][]byte, handWritten map[string]bool) ([]string, error) {
	var stale []string
	err := filepath.WalkDir(dir, func(file string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		path, err := filepath.Rel(dir, file)
		if err != nil {
			return err
		}
		path = filepath.ToSlash(path)
		if _, ok := rendered[path]; !ok && !handWritten[path] {
			stale = append(stale, path)
		}
		return nil
	})
	return stale, err
}

func gatewayAPI(g profile.GatewayAPI) ([]byte, error) {
	client := &http.Client{Timeout: time.Minute}
	resp, err := client.Get(g.URL())
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", g.URL(), resp.Status)
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, fmt.Errorf("GET %s: %w", g.URL(), err)
	}
	sum := sha256.Sum256(body)
	if got := hex.EncodeToString(sum[:]); got != g.SHA256 {
		return nil, fmt.Errorf("%s has sha256 %s, pinned %s", g.URL(), got, g.SHA256)
	}
	header := fmt.Sprintf("%s# Source: %s\n# Version: %s, %s channel\n# sha256: %s\n", generated, g.URL(), g.Version, g.Channel, g.SHA256)
	return append([]byte(header), body...), nil
}

// chart renders c the way helm template does, with hooks included as plain
// manifests. The chart is pulled into memory first; nothing parses Helm's
// command-line output.
func chart(reg *registry.Client, c profile.Chart) ([]byte, error) {
	ref := strings.TrimPrefix(c.Ref, "oci://") + ":" + c.Version
	pulled, err := reg.Pull(ref)
	if err != nil {
		return nil, fmt.Errorf("pull %s: %w", ref, err)
	}
	if pulled.Manifest.Digest != c.Digest {
		return nil, fmt.Errorf("chart %s has manifest digest %s, pinned %s", ref, pulled.Manifest.Digest, c.Digest)
	}
	ch, err := loader.LoadArchive(bytes.NewReader(pulled.Chart.Data))
	if err != nil {
		return nil, fmt.Errorf("load %s: %w", ref, err)
	}
	vals := map[string]any{}
	for _, s := range c.Set {
		if err := strvals.ParseInto(s, vals); err != nil {
			return nil, fmt.Errorf("%s value %q: %w", ref, s, err)
		}
	}
	install := action.NewInstall(action.NewConfiguration())
	install.DryRunStrategy = action.DryRunClient
	install.Replace = true
	install.ReleaseName = c.Release
	install.Namespace = c.Namespace
	r, err := install.Run(ch, vals)
	if err != nil {
		return nil, fmt.Errorf("template %s: %w", ref, err)
	}
	rel, ok := r.(*release.Release)
	if !ok {
		return nil, fmt.Errorf("template %s: unexpected release type %T", ref, r)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "%s# Source: %s %s\n# sha256: %s\n# Values: %s\n", generated, c.Ref, c.Version, strings.TrimPrefix(c.Digest, "sha256:"), strings.Join(c.Set, " "))
	if c.Namespace != "" {
		fmt.Fprintf(&b, "---\napiVersion: v1\nkind: Namespace\nmetadata:\n  name: %s\n", c.Namespace)
	}
	fmt.Fprintf(&b, "%s\n", strings.TrimSpace(rel.Manifest))
	for _, h := range rel.Hooks {
		fmt.Fprintf(&b, "---\n# Source: %s\n%s\n", h.Path, strings.TrimSpace(h.Manifest))
	}
	out := b.Bytes()
	if c.StripCELValidations {
		stripped, err := stripCELValidations(out)
		if err != nil {
			return nil, fmt.Errorf("strip CEL validations from %s: %w", ref, err)
		}
		out = stripped
	}
	return out, nil
}

// stripCELValidations removes every x-kubernetes-validations key from the
// YAML documents in data. Headers and comments before the first document are
// kept.
func stripCELValidations(data []byte) ([]byte, error) {
	const key = "x-kubernetes-validations"
	parts := bytes.Split(data, []byte("\n---\n"))
	var out bytes.Buffer
	wroteDoc := false
	for i, part := range parts {
		doc := bytes.TrimSpace(bytes.TrimPrefix(bytes.TrimPrefix(part, []byte("---\n")), []byte("---")))
		if i == 0 {
			// Keep the generated header comments; only rewrite from the first
			// document.
			if idx := bytes.Index(doc, []byte("\napiVersion:")); idx >= 0 {
				out.Write(doc[:idx+1])
				doc = bytes.TrimSpace(doc[idx+1:])
			} else if !bytes.HasPrefix(doc, []byte("apiVersion:")) {
				if len(doc) > 0 {
					out.Write(doc)
					if !bytes.HasSuffix(doc, []byte("\n")) {
						out.WriteByte('\n')
					}
				}
				continue
			}
		}
		if len(doc) == 0 {
			continue
		}
		var obj any
		if err := yaml.Unmarshal(doc, &obj); err != nil {
			return nil, err
		}
		if obj == nil {
			continue
		}
		removeKey(obj, key)
		encoded, err := yaml.Marshal(obj)
		if err != nil {
			return nil, err
		}
		if wroteDoc {
			out.WriteString("---\n")
		}
		out.Write(encoded)
		if !bytes.HasSuffix(encoded, []byte("\n")) {
			out.WriteByte('\n')
		}
		wroteDoc = true
	}
	return out.Bytes(), nil
}

func removeKey(v any, key string) {
	switch v := v.(type) {
	case map[string]any:
		delete(v, key)
		for _, child := range v {
			removeKey(child, key)
		}
	case []any:
		for _, child := range v {
			removeKey(child, key)
		}
	}
}
